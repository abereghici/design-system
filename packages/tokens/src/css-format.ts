import type { Dictionary, TransformedToken } from "style-dictionary/types";

import { compositeCss } from "./composite.ts";
import { mediaOverrides, perTheme } from "./media.ts";
import { componentOf } from "./naming.ts";
import { propertyRules } from "./property.ts";
import { authoredDark, isThemed, referencedToken, resolvedDark } from "./theme.ts";
import { inTierOrder, tierOf } from "./tiers.ts";

const cssValue = (
  token: TransformedToken,
  authored: unknown,
  literal: unknown,
  dictionary: Dictionary,
): string => {
  const target = referencedToken(authored, dictionary);

  if (target) return `var(--${target.name})`;

  if (typeof authored === "object" && authored !== null && tierOf(token) !== "primitive") {
    return compositeCss(token.$type, authored, dictionary);
  }

  return String(literal);
};

const declaration = (token: TransformedToken, dictionary: Dictionary): string => {
  const light = cssValue(token, token.original.$value, token.$value, dictionary);
  const dark = isThemed(token)
    ? cssValue(token, authoredDark(token), resolvedDark(token), dictionary)
    : light;
  const value = dark === light ? light : `light-dark(${light}, ${dark})`;

  return `    --${token.name}: ${value};`;
};

interface MediaEntry {
  readonly token: TransformedToken;
  readonly query: string;
  readonly value: unknown;
}

const overrideCss = (entry: MediaEntry, dictionary: Dictionary): string => {
  const ref = (value: unknown) => cssValue(entry.token, value, value, dictionary);
  const themes = perTheme(entry.value);
  const css = themes ? `light-dark(${ref(themes.light)}, ${ref(themes.dark)})` : ref(entry.value);

  return `      --${entry.token.name}: ${css};`;
};

const mediaBlocks = (tokens: readonly TransformedToken[], dictionary: Dictionary): string[] => {
  const entries: MediaEntry[] = tokens.flatMap((token) =>
    mediaOverrides(token).map(({ query, value }) => ({ token, query, value })),
  );
  const byQuery = Map.groupBy(entries, (entry: MediaEntry) => entry.query);

  return [...byQuery.keys()].flatMap((query) => [
    "",
    `  @media ${query} {`,
    "    :root {",
    ...(byQuery.get(query) ?? []).map((entry: MediaEntry) => overrideCss(entry, dictionary)),
    "    }",
    "  }",
  ]);
};

const HEADER =
  "/* @platform/tokens. Generated by Style Dictionary from src/tokens; do not edit. */";

const declarations = (tokens: readonly TransformedToken[], dictionary: Dictionary): string[] =>
  tokens.map((token) => declaration(token, dictionary));

const sharedCss = (tokens: readonly TransformedToken[], dictionary: Dictionary): string =>
  [
    HEADER,
    "@layer ab.tokens {",
    "  :root {",
    "    color-scheme: light dark;",
    ...declarations(tokens, dictionary),
    "  }",
    "",
    '  [data-theme="light"] {',
    "    color-scheme: light;",
    "  }",
    "",
    '  [data-theme="dark"] {',
    "    color-scheme: dark;",
    "  }",
    ...mediaBlocks(tokens, dictionary),
    "}",
    "",
  ].join("\n");

const componentCss = (tokens: readonly TransformedToken[], dictionary: Dictionary): string =>
  [
    HEADER,
    ...propertyRules(tokens, dictionary),
    "@layer ab.tokens {",
    "  :root {",
    ...declarations(tokens, dictionary),
    "  }",
    "}",
    "",
  ].join("\n");

export const stylesheets = (dictionary: Dictionary) => {
  const { "": shared = [], ...components } = Object.groupBy(
    inTierOrder(dictionary.allTokens),
    (token) =>
      tierOf(token) === "component" ? String(componentOf(token.path.slice(1).join("-"))) : "",
  );

  return {
    css: sharedCss(shared, dictionary),
    components: Object.fromEntries(
      Object.keys(components).map((name) => [
        name,
        componentCss(components[name] ?? [], dictionary),
      ]),
    ),
  };
};
