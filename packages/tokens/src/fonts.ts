// The latin and latin-ext ranges overlap on U+0304, U+0308 and U+0329, so latin is declared last and wins, as in Google's sheet.
export const FONT_SUBSETS = [
  {
    name: "latin-ext",
    unicodeRange:
      "U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C4, U+2113, U+2C60-2C7F, U+A720-A7FF",
  },
  {
    name: "latin",
    unicodeRange:
      "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD",
  },
] as const;

type FontSubset = (typeof FONT_SUBSETS)[number];

interface FontFamily {
  readonly family: string;
  readonly stem: string;
  readonly weight: string;
  readonly stretch?: string;
}

export const FONT_FAMILIES = [
  { family: "Figtree", stem: "Figtree", weight: "300 900" },
  { family: "Noto Serif", stem: "NotoSerif", weight: "100 900", stretch: "62.5% 100%" },
] as const satisfies readonly FontFamily[];

export const FONT_STYLES = ["normal", "italic"] as const;

type FontStyle = (typeof FONT_STYLES)[number];

export function fontFileName(family: FontFamily, subset: FontSubset, style: FontStyle): string {
  return `${family.stem}${style === "italic" ? "-Italic" : ""}-${subset.name}.woff2`;
}

export function codePointsIn(unicodeRange: string): number[] {
  return unicodeRange.split(", ").flatMap((part) => {
    const [first = "", last = first] = part.replace("U+", "").split("-");
    const start = Number.parseInt(first, 16);

    return Array.from(
      { length: Number.parseInt(last, 16) - start + 1 },
      (_, index) => start + index,
    );
  });
}

function fontFace(
  family: FontFamily,
  style: FontStyle,
  subset: FontSubset,
  fontsUrl: string,
): string {
  const descriptors = [
    `font-family: "${family.family}";`,
    `font-style: ${style};`,
    `font-weight: ${family.weight};`,
    ...(family.stretch === undefined ? [] : [`font-stretch: ${family.stretch};`]),
    "font-display: swap;",
    `src: url("${fontsUrl}${fontFileName(family, subset, style)}") format("woff2");`,
    `unicode-range: ${subset.unicodeRange};`,
  ];

  return `/* ${family.family} ${style} ${subset.name} */\n@font-face {\n${descriptors.map((line) => `  ${line}`).join("\n")}\n}\n`;
}

export function fontFaceCss(fontsUrl = "../fonts/"): string {
  const faces = FONT_FAMILIES.flatMap((family) =>
    FONT_STYLES.flatMap((style) =>
      FONT_SUBSETS.map((subset) => fontFace(family, style, subset, fontsUrl)),
    ),
  );

  return [
    "/* Figtree and Noto Serif, variable, SIL Open Font License 1.1 (fonts/Figtree-OFL.txt, fonts/NotoSerif-OFL.txt). Generated by @platform/tokens; do not edit. */\n",
    ...faces,
  ].join("\n");
}
