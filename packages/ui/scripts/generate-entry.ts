import { globSync } from "node:fs";

import { format } from "oxfmt";

import formatConfig from "../../../oxfmt.config.ts";

// The sources of the public subpaths, as `exports` maps them.
const SUBPATHS = ["src/*/index.ts", "src/components/*/index.ts"];

const ICONS = "src/components/icon/icons/*.tsx";

/** `src/index.ts`: the root entry, re-exporting every public subpath. */
export async function generateEntry() {
  const cwd = new URL("..", import.meta.url);
  const sources = [
    ...globSync(SUBPATHS, { cwd }).toSorted(),
    ...globSync(ICONS, { cwd }).toSorted(),
  ];
  const exports = sources.map((path) => `export * from "./${path.slice("src/".length)}";`);
  const text = `// Generated by \`pnpm entry\`. One entry for tools such as /design-sync; apps import the subpaths (ADR-0009).\n${exports.join("\n\n")}\n`;
  const result = await format("src/index.ts", text, formatConfig);

  if (result.errors.length > 0) throw new Error(`src/index.ts: ${JSON.stringify(result.errors)}`);

  return result.code;
}
